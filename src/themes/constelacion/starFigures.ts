/** Each song keeps its own animal: the same id always gets the same one. */
export function figureIndexFor(id: string | undefined) {
  if (!id) return 0;
  let hash = 0;
  for (let i = 0; i < id.length; i += 1) {
    hash = (hash * 31 + id.charCodeAt(i)) | 0;
  }
  return Math.abs(hash) % starFigures.length;
}
